-- Layer:         Canonical Spine (Immutable Business Truth)
-- Purpose:       Represents a sellable item in the company's product catalog.
--                 Products are real-world nouns that exist independent of the
--                 platform. They derive from product catalog, SKU systems,
--                 and billing platforms. This table stores only immutable
--                 business truth — no derived scores, no AI opinion, no JSONB
--                 blobs. Relationships are stored in spine_relationships.
-- Source:        SPINE_DOMAIN.md §3.1, §3.4
--                 SPINE_INTELLIGENCE_AGENT.md §10.2 (spine_*.sql emission)
