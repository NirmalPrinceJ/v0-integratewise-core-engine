    version         INTEGER NOT NULL DEFAULT 1,       -- append-only versioning; time-travel and audit support

    -- ── Immutable business truth ────────────────────────────────────────────────
    title           TEXT NOT NULL,                    -- human-readable task name
    description     TEXT,                             -- detailed description / notes
    status          TEXT NOT NULL DEFAULT 'open',    -- open, in_progress, completed, cancelled, blocked, deferred
    priority        TEXT,                             -- low, medium, high, urgent
    task_type       TEXT,                             -- follow_up, onboarding, support, qbr_prep, renewal, escalation, internal, external, custom
    due_date        TEXT,                             -- ISO 8601 date (YYYY-MM-DD) when task is due
    completed_at    INTEGER,                        -- Unix timestamp (seconds) when task was completed
    source_system   TEXT,                             -- origin system: 'salesforce', 'hubspot', 'asana', 'jira', 'notion', 'monday', 'manual', etc.
    external_id     TEXT,                             -- record ID in the source system (e.g., Salesforce Task ID)

    -- ── System / provenance ─────────────────────────────────────────────────
    provenance      JSON NOT NULL DEFAULT '{}',       -- { source: "salesforce", record_id: "00Txxx", sync_version: "v2" }
    created_at      INTEGER,                          -- Unix timestamp (seconds since epoch)
    updated_at      INTEGER                           -- Unix timestamp (seconds since epoch)
);

