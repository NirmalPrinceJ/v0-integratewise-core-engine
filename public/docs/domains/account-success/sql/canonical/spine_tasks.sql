CREATE TABLE IF NOT EXISTS spine_tasks (
    -- ── Core identity ─────────────────────────────────────────────────────────
    id              TEXT PRIMARY KEY,                 -- UUID as text (assigned by pipeline)
    tenant_id       TEXT NOT NULL,                    -- tenant scoping (cross-tenant impossible by construction)
